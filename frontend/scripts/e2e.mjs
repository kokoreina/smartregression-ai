async function mail(context, email, expected) {
  const deadline = Date.now() + 10000
  while (Date.now() < deadline) {
    const response = await context.request.get(`${origin}/__test__/mail?email=${encodeURIComponent(email)}`, { headers: { 'X-Test-Inbox': 'synthetic-e2e-only' } })
    const data = await response.json()
    const message = data.messages?.findLast(item => item.body.includes(expected))
    if (message) {
      const link = message.body.trim()
      assert(link.startsWith(origin + '/' + expected + '#token='))
      return link
    }
    await new Promise(resolve => setTimeout(resolve, 250))
  }
  throw new Error('SMTP test inbox did not receive expected message')
}

